package ec.rehabelite.audit.domain;

import java.time.Instant;
import java.util.List;
import org.springframework.data.jpa.repository.JpaRepository;
import org.springframework.data.jpa.repository.JpaSpecificationExecutor;
import org.springframework.data.jpa.repository.Modifying;
import org.springframework.data.jpa.repository.Query;
import org.springframework.data.repository.query.Param;

/** Read and insert only: the database rejects UPDATE, DELETE and TRUNCATE on audit_logs (trigger of V1). */
public interface AuditLogRepository extends JpaRepository<AuditLog, Long>, JpaSpecificationExecutor<AuditLog> {

    /** The entity types that appear in the log, for the entity filter. */
    @Query("SELECT DISTINCT a.entityType FROM AuditLog a ORDER BY a.entityType")
    List<String> findDistinctEntityTypes();

    /**
     * One entry per entity id, all of them in a single INSERT: the ids are generated by the database (identity), so
     * Hibernate cannot batch a saveAll, and a list would cost one statement per entry. The casts give a type to the
     * parameters that may be null. Returns the number of entries inserted.
     */
    @Modifying
    @Query(nativeQuery = true, value = """
            INSERT INTO audit_logs (user_id, action, entity_type, entity_id, occurred_at, ip_address)
            SELECT CAST(:userId AS bigint), :action, :entityType, ids.entity_id, :occurredAt,
                   CAST(:ipAddress AS varchar)
            FROM unnest(CAST(:entityIds AS bigint[])) AS ids (entity_id)""")
    int insertAll(@Param("userId") Long userId, @Param("action") String action,
            @Param("entityType") String entityType, @Param("entityIds") Long[] entityIds,
            @Param("occurredAt") Instant occurredAt, @Param("ipAddress") String ipAddress);

}
